/** Adds each label's explanation to detail items that don't carry their own. */
export const withHelp = <T extends { label: string; hint?: string }>(items: T[]): T[] => items.map((it) => ({ hint: DETAIL_HELP[it.label], ...it }));

/** Labels whose value is a name or address worth copying (DET-03). */
const COPYABLE = /host|endpoint|url|address|secret|keys|username|database|bucket|image|commit|name servers|port|private ip|dns|key$|zone id|subject|stream|consumer|hostname/i;

export const isCopyable = (label: string) => COPYABLE.test(label);
/** Labels whose value names a secret of the same project, so it can link to it. */
export const isSecretLabel = (label: string) => /secret$|^bucket keys$/i.test(label);
/** Labels shown in the code font. */
export const isMono = (label: string) => /host|endpoint|url|address|image|secret|keys|bucket|username|database|commit|sha-256|subject|stream|consumer|zone id|name servers|key prefix|command/i.test(label);
